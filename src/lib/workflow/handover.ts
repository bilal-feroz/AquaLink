/**
 * Shift handover and work-order documents, generated from current state only.
 */
import { FACILITY, FLOW_THRESHOLDS, PUMPS, TANKS, TECHNICIANS } from "@/lib/data/facility";
import { clock, duration, hm } from "@/lib/format";
import type { IncidentRuntime, SimState } from "@/lib/simulation/engine";
import { activeIncidents } from "@/lib/simulation/engine";
import { facilityKpis } from "@/lib/simulation/kpi";
import { pumpReading, tankReading } from "@/lib/simulation/readings";
import { ASSET_BY_ID, PUMP_BY_ID, TANK_BY_ID } from "@/lib/topology/graph";
import type { ActivityEntry, IncidentMeta, MaintenanceTask, WorkOrder } from "./types";

export function techName(id?: string) {
  if (!id) return "Unassigned";
  return TECHNICIANS.find((t) => t.id === id)?.name ?? id;
}

export function pumpStateLabel(s: SimState, id: string) {
  const p = s.pumps[id];
  const cfg = PUMP_BY_ID[id];
  switch (p.mode) {
    case "running":
      return p.covering ? `Backup active (${Math.round(p.output * 100)}% rated)` : "Online";
    case "starting":
      return p.covering ? "Backup starting" : "Starting";
    case "stopping":
      return "Returning to standby";
    case "standby":
      return cfg.role === "backup" ? "Standby" : "Stopped";
    case "tripping":
      return "Overcurrent";
    case "fault":
      return "Fault — stopped";
  }
}

/** State label for any incident root asset (pump or filter). */
export function rootStateLabel(s: SimState, id: string) {
  if (s.pumps[id]) return pumpStateLabel(s, id);
  const f = s.filters?.[id];
  if (f) return f.backwashing ? "Backwashing" : f.clog > 0.02 ? `Blocked (${Math.round(f.clog * 100)}%)` : "In service";
  return "";
}

interface HandoverInput {
  sim: SimState;
  tasks: MaintenanceTask[];
  workOrders: WorkOrder[];
  incidentMeta: Record<string, IncidentMeta>;
  activity: ActivityEntry[];
  preparedBy: string;
}

export function buildHandover({ sim, tasks, workOrders, incidentMeta, activity, preparedBy }: HandoverInput): string {
  const k = facilityKpis(sim);
  const active = activeIncidents(sim);
  const lines: string[] = [];
  lines.push(`# Shift handover — ${FACILITY.name}`);
  lines.push("");
  lines.push(`Prepared by ${preparedBy} at ${clock(sim.t)} (simulated scenario time). Generated by AquaLink from the current digital-twin state.`);
  lines.push("");
  lines.push("## Summary");
  if (active.length === 0) {
    lines.push(`- No active incidents. All ${TANKS.length} tanks at design circulation.`);
  } else {
    for (const inc of active) lines.push(`- **${inc.id} — ${inc.title}** (${inc.status === "recovering" ? "recovering" : "active"}, open ${duration(sim.t - inc.openedAt)})`);
  }
  lines.push(`- Facility circulation ${k.aggregateFlowDisplay}% of design (equal-weighted); ${k.affectedTankIds.length} tank(s) below ${FLOW_THRESHOLDS.healthy}%.`);
  lines.push(`- Average temperature ${k.avgTemp.toFixed(1)} °C · mean pH ${k.meanPh.toFixed(2)} · mean DO ${k.meanDo.toFixed(1)} mg/L.`);
  lines.push("");

  for (const inc of active) lines.push(...incidentSection(sim, inc, tasks, workOrders, incidentMeta[inc.id]));

  lines.push("## Equipment status");
  for (const p of PUMPS) {
    const r = pumpReading(sim, p.id);
    lines.push(`- ${p.name}: ${pumpStateLabel(sim, p.id)} · ${Math.round(r.delivered)} m³/h delivered`);
  }
  lines.push("");
  lines.push("## Tank circulation");
  lines.push("| Tank | Habitat | Circulation | Temp °C | pH | DO mg/L |");
  lines.push("|---|---|---|---|---|---|");
  for (const t of TANKS) {
    const r = tankReading(sim, t.id);
    lines.push(`| ${t.name} | ${t.habitat.name} | ${Math.round(r.flowPct)}% | ${r.temp.toFixed(1)} | ${r.ph.toFixed(1)} | ${r.dissolvedO2.toFixed(1)} |`);
  }
  lines.push("");

  const recent = sim.events.slice(-8);
  if (recent.length) {
    lines.push("## Recent significant events");
    for (const e of recent) lines.push(`- ${hm(e.t)} — ${e.title}`);
    lines.push("");
  }

  const recentActivity = activity.slice(-8);
  if (recentActivity.length) {
    lines.push("## Technician activity this shift");
    for (const a of recentActivity) lines.push(`- ${hm(a.at)} — ${a.by}: ${a.text}`);
    lines.push("");
  }

  lines.push("---");
  lines.push("All operational values are from the AquaLink demonstration simulation, not live plant measurements. Recommended actions are decision support only and do not authorise remote operation of life-support equipment.");
  return lines.join("\n");
}

function incidentSection(sim: SimState, inc: IncidentRuntime, tasks: MaintenanceTask[], wos: WorkOrder[], meta?: IncidentMeta): string[] {
  const out: string[] = [];
  const root = ASSET_BY_ID[inc.rootAssetId];
  const backup = inc.backupPumpId ? sim.pumps[inc.backupPumpId] : undefined;
  out.push(`## ${inc.id} — ${inc.title}`);
  out.push(`- Opened ${hm(inc.openedAt)} · owner ${techName(meta?.ownerId)}${meta?.acknowledgedAt ? ` · acknowledged ${hm(meta.acknowledgedAt)}` : " · not acknowledged"}`);
  out.push(`- Failed equipment: ${root.name} (${root.id}) — ${rootStateLabel(sim, root.id)}`);
  out.push(`- Root cause: ${inc.diagnosis.label} — ${inc.diagnosis.confidence}`);
  out.push(`- Affected tanks: ${inc.affectedTankIds.map((id) => `${TANK_BY_ID[id].name} ${Math.round(sim.tanks[id].flowPct)}%`).join(", ") || "none"}`);
  if (backup && inc.backupPumpId) {
    const minFlow = Math.min(...inc.affectedTankIds.map((id) => sim.tanks[id].flowPct));
    out.push(
      `- Backup: ${PUMP_BY_ID[inc.backupPumpId].code} ${pumpStateLabel(sim, inc.backupPumpId).toLowerCase()} — temporary, partial support; ${
        minFlow >= FLOW_THRESHOLDS.emergencyMinimum ? "meets" : "below"
      } the ${FLOW_THRESHOLDS.emergencyMinimum}% demonstration emergency threshold`,
    );
  }
  const itasks = tasks.filter((t) => t.incidentId === inc.id).sort((a, b) => a.priority - b.priority);
  const done = itasks.filter((t) => t.status === "done");
  const pending = itasks.filter((t) => t.status !== "done");
  out.push("");
  out.push("**Completed tasks**");
  if (done.length === 0) out.push("- None yet");
  for (const t of done) out.push(`- ✓ ${t.title} — ${techName(t.assigneeId)}${t.completedAt ? ` at ${hm(t.completedAt)}` : ""}`);
  out.push("");
  out.push("**Pending tasks**");
  if (pending.length === 0) out.push("- None");
  for (const t of pending) {
    const stepsDone = t.steps.filter((s) => s.done).length;
    out.push(`- [${t.status === "in-progress" ? "in progress" : t.status}] P${t.priority} ${t.title} — ${techName(t.assigneeId)} (${stepsDone}/${t.steps.length} steps)`);
  }
  const notes = [...(meta?.notes ?? []), ...itasks.flatMap((t) => t.notes.map((n) => ({ ...n, text: `${n.text} (${t.id})` })))].sort((a, b) => a.at - b.at);
  out.push("");
  out.push("**Technician notes**");
  if (notes.length === 0) out.push("- None recorded");
  for (const n of notes) out.push(`- ${hm(n.at)} ${n.by}: ${n.text}`);
  const iwos = wos.filter((w) => w.incidentId === inc.id);
  if (iwos.length) {
    out.push("");
    out.push("**Work orders**");
    for (const w of iwos) out.push(`- ${w.id} (${w.status}, simulated) — ${w.title} · ${techName(w.assigneeId)}`);
  }
  out.push("");
  return out;
}

export function buildWorkOrderContext(sim: SimState, inc: IncidentRuntime): string[] {
  const root = ASSET_BY_ID[inc.rootAssetId];
  const lines = [
    `Incident ${inc.id} opened ${hm(inc.openedAt)} (${duration(sim.t - inc.openedAt)} at time of issue)`,
    `${root.name}: ${rootStateLabel(sim, root.id)} — ${inc.diagnosis.label} (${inc.diagnosis.confidence})`,
    ...inc.affectedTankIds.map((id) => `${TANK_BY_ID[id].name}: ${Math.round(sim.tanks[id].flowPct)}% circulation`),
  ];
  if (inc.backupPumpId) lines.push(`${PUMP_BY_ID[inc.backupPumpId].code}: ${pumpStateLabel(sim, inc.backupPumpId)}`);
  return lines;
}

export function workOrderText(w: WorkOrder): string {
  return [
    `WORK ORDER ${w.id} — SIMULATED`,
    `Status: ${w.status}`,
    `Priority: ${w.priority}`,
    `Incident: ${w.incidentId}`,
    `Asset: ${w.assetId}`,
    `Assigned to: ${techName(w.assigneeId)}`,
    `Raised at: ${clock(w.createdAt)} by ${w.createdBy}`,
    "",
    w.title,
    "",
    w.description,
    "",
    "Requested actions:",
    ...w.requestedActions.map((a, i) => `${i + 1}. ${a}`),
    "",
    "Context at time of issue (simulated):",
    ...w.context.map((c) => `- ${c}`),
    "",
    "This work order was generated by the AquaLink demonstration and is not connected to a CMMS.",
  ].join("\n");
}
